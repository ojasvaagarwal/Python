a = True
b = False

print("Addition:", a + b, type(a + b))
print("Subtraction:", a - b, type(a - b))
print("Multiplication:", a * b, type(a * b))
print("Division:", b / a, type(b / a))
print("Floor Division:", a // a, type(a // a))
print("Modulus:", a % a, type(a % a))
print("Exponentiation:", a ** b, type(a ** b))